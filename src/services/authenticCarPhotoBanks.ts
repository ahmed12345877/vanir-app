  const combined = `${cleanId} ${cleanName}`;

  if (combined.includes('amg') || combined.includes('gt 63') || combined.includes('gt63')) {
    return AUTHENTIC_CAR_PHOTO_BANKS['mercedes-amg-gt63s'];
  }
