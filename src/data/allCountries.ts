export interface MasterCountry {
  iso: string; // ISO alpha-2 (upper-case)
  en: string;
  ar: string;
  continent: ContinentKey;
  iata: string; // '' when the country has no commercial airport
  cityEn: string;
  cityAr: string;
  airportAr: string;
}

/** 🇪🇬 from "EG" */
export function isoToFlag(iso: string): string {
  const up = iso.toUpperCase();
  if (up.length !== 2) return '🌐';
  return String.fromCodePoint(up.charCodeAt(0) - 65 + 0x1f1e6, up.charCodeAt(1) - 65 + 0x1f1e6);
}

