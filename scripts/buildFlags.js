// Usage: node scripts/buildFlags.js
// Reads every Flagpack SVG in /icon and generates src/data/flagSvgs.ts
// (ISO-2 code -> minified SVG string, cropped to a 4:3 flag viewBox).
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIRS = [
  path.join(ROOT, 'icon', 'streamline-flagpack--24x24-SVG'),
  path.join(ROOT, 'icon', 'streamline-flagpack--24x24-SVG (1)'),
];

const out = {};
for (const dir of DIRS) {
  if (!fs.existsSync(dir)) continue;
  for (const file of fs.readdirSync(dir)) {
    if (!file.toLowerCase().endsWith('.svg')) continue;
    const base = file.replace(/--Streamline.*$/i, '');
    const parts = base.split('-');
    const iso = parts[0].toUpperCase();
    if (iso.length !== 2) continue;
    // For the UK keep the classic Union Jack ("Ukm"); skip England/Scotland/etc.
    if (iso === 'GB' && !/^Gb-Ukm/i.test(base)) continue;
    // Skip Caribbean Netherlands sub-variants, keep a single entry per ISO code.
    if (out[iso] && iso !== 'GB') continue;
    let svg = fs.readFileSync(path.join(dir, file), 'utf8');
    svg = svg
      .replace(/<desc>[\s\S]*?<\/desc>/g, '')
      .replace(/\sid="[^"]*Streamline-Flagpack"/g, '')
      .replace(/\sheight="24"\swidth="24"/, '')
      .replace(/viewBox="0 0 32 32"/, 'viewBox="0 4 32 24"')
      .replace(/>\s+</g, '><')
      .replace(/\s+/g, ' ')
      .trim();
    out[iso] = svg;
  }
}

const keys = Object.keys(out).sort();
let ts = '/* AUTO-GENERATED by scripts/buildFlags.js — do not edit by hand. */\n';
ts += `export const FLAG_SVGS: Record<string, string> = {\n`;
for (const k of keys) {
  ts += `  ${k}: ${JSON.stringify(out[k])},\n`;
}
ts += '};\n';
fs.writeFileSync(path.join(ROOT, 'src', 'data', 'flagSvgs.ts'), ts);
console.log(`Generated ${keys.length} flags:`, keys.join(' '));
